create table public.staff_prices (
  id bigint generated by default as identity primary key,
  excursion_id bigint not null references public.excursions(id) on delete cascade,
  staff_type text not null check (staff_type in ('driver','guide')),
  min_passengers integer not null default 0,
  max_passengers integer,
  price numeric(10,2) not null,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (min_passengers >= 0),
  check (max_passengers is null or max_passengers >= min_passengers),
  unique nulls not distinct (excursion_id, staff_type, min_passengers, max_passengers)
