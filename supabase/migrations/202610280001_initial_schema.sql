create table public.bookings (
  id bigint generated by default as identity primary key,
  excursion_id bigint not null references public.excursions(id) on delete cascade,
  weekday smallint check (weekday between 1 and 7),
  time time,
  excursion_date date,
  bus_seat_id bigint not null references public.bus_seats(id) on delete restrict,
  booked_by bigint not null references public.profiles(id) on delete restrict,
  price numeric(10,2) not null check (price >= 0),
  debt numeric(10,2) not null default 0 check (debt >= 0),
  customer_name text not null,
  customer_phone text not null,
  comment text,
  passenger_type text not null default 'adult' check (passenger_type in ('adult','child','senior','disabled','special','concession')),
  with_entry boolean not null default false,
  stop_id bigint not null references public.stops(id),
  booked_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  check (debt <= price)
);

