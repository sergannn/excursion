create table public.bus_seats (
  id bigint generated by default as identity primary key,
  excursion_id bigint not null references public.excursions(id) on delete cascade,
  seat_number integer not null check (seat_number > 0),
  status text not null default 'available' check (status in ('available','booked','reserved')),
  booked_by bigint references public.profiles(id) on delete set null,
  booked_at timestamptz,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
